/** Типограф: неразрывный пробел после однобуквенных слов и перед длинным тире. */
export function t(text: string) {
  return text
    .replace(/(^|[\s(« ])([вкосуиаяВКОСУИАЯ])\s/g, "$1$2 ")
    .replace(/(^|[\s(« ])([вкосуиаяВКОСУИАЯ])\s/g, "$1$2 ")
    .replace(/\s—\s/g, " — ")
    .replace(/(\d)\s(м²)/g, "$1 $2");
}

